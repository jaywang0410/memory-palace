// ===== 关联关系自动计算 =====
export function computeRelations(stars: StarMemory[]): StarMemory[] {
  return stars.map((star) => {
    const related: string[] = []

    for (const other of stars) {
      if (other.id === star.id) continue

      let score = 0

      // 同一场景
      if (other.scene === star.scene) score += 2

      // 同一人物
      const commonPeople = other.people.filter((p) => star.people.includes(p))
      if (commonPeople.length > 0) score += commonPeople.length

      // 相近时间（简化：同一天或相邻条目）
      const starIndex = stars.findIndex((s) => s.id === star.id)
      const otherIndex = stars.findIndex((s) => s.id === other.id)
      if (Math.abs(starIndex - otherIndex) <= 3) score += 1

      // 相似情感
      if (other.emotion === star.emotion) score += 1

      // 同一星座
      if (other.constellation === star.constellation) score += 0.5

      if (score >= 2) {
        related.push(other.id)
      }
    }

    // 最多保留 5 个关联
    return { ...star, relatedStarIds: related.slice(0, 5) }
  })
}

export const ENRICHED_STAR_MEMORIES = computeRelations(STAR_MEMORIES)
